"""Planner benchmark: CP-SAT optimiser vs greedy-priority and FIFO baselines (Task 7.6, G7).

Every number this writes comes from this run. For each seeded synthetic scenario it builds one
feasibility matrix, runs the three planners on the stored (not fused) scenario, checks every plan
with the independent validator, and records the plan KPIs and wall time.

    cd backend && python ../benchmarks/run_benchmarks.py --scenarios 20 --seed 1

Writes benchmarks/results/results.csv and benchmarks/RESULTS.md (overwritten each run).
"""

from __future__ import annotations

import argparse
import csv
import os
import platform
import statistics as st
import sys
import time
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.models.scenario import GeneratorParams  # noqa: E402
from app.models.store import scenario_id_for  # noqa: E402
from app.planning.context import PlanningContext  # noqa: E402
from app.planning.feasibility import build_matrix  # noqa: E402
from app.planning.greedy import plan as greedy_plan  # noqa: E402
from app.planning.optimiser import SolveParams, solve  # noqa: E402
from app.planning.validate import validate_plan  # noqa: E402
from app.sim.generate import generate_scenario  # noqa: E402

PLANNERS = ("fifo", "greedy", "cpsat")
OUT_DIR = Path(__file__).resolve().parent
FIELDS = [
    "seed", "scenario_id", "planner", "missions_total", "missions_covered",
    "priority_weighted_coverage", "mean_risk", "aircraft_utilisation", "wall_s", "solver_status",
    "violations",
]


def run_one(seed: int, time_limit: float, workers: int) -> list[dict]:
    scenario = generate_scenario(GeneratorParams(seed=seed))
    sid = scenario_id_for(scenario)
    ctx = PlanningContext(scenario)
    matrix = build_matrix(ctx)
    rows = []
    for name in PLANNERS:
        start = time.perf_counter()
        if name == "cpsat":
            p = solve(ctx, sid, SolveParams(time_limit_s=time_limit, num_workers=workers, seed=0), matrix)
        else:
            p = greedy_plan(ctx, sid, "fifo" if name == "fifo" else "greedy_priority", matrix)
        wall = time.perf_counter() - start
        k = p.kpis
        rows.append({
            "seed": seed, "scenario_id": sid, "planner": name,
            "missions_total": k.missions_total, "missions_covered": k.missions_covered,
            "priority_weighted_coverage": round(k.priority_weighted_coverage, 4),
            "mean_risk": round(k.mean_risk, 4), "aircraft_utilisation": round(k.aircraft_utilisation, 4),
            "wall_s": round(wall, 2), "solver_status": p.solver.status or "",
            "violations": len(validate_plan(scenario, p)),
        })
    return rows


def summarise(rows: list[dict], args: argparse.Namespace, started: str, elapsed: float) -> str:
    by = {n: [r for r in rows if r["planner"] == n] for n in PLANNERS}
    seeds = sorted({r["seed"] for r in rows})
    pwc = {n: [r["priority_weighted_coverage"] for r in by[n]] for n in PLANNERS}
    cov = {n: [r["missions_covered"] for r in by[n]] for n in PLANNERS}
    risk = {n: [r["mean_risk"] for r in by[n] if r["missions_covered"]] for n in PLANNERS}
    viol = sum(r["violations"] for r in rows)

    def rel(a: str, b: str) -> list[float]:  # per-scenario relative gain of a over b, where b > 0
        return [(x - y) / y for x, y in zip(pwc[a], pwc[b], strict=True) if y > 0]

    def wins(a: str, b: str) -> tuple[int, int, int]:
        pairs = list(zip(pwc[a], pwc[b], strict=True))
        return (sum(x > y + 1e-9 for x, y in pairs), sum(abs(x - y) <= 1e-9 for x, y in pairs),
                sum(x < y - 1e-9 for x, y in pairs))

    statuses: dict[str, int] = {}
    for r in by["cpsat"]:
        statuses[r["solver_status"]] = statuses.get(r["solver_status"], 0) + 1
    t = [r["wall_s"] for r in by["cpsat"]]
    pct = lambda v: f"{v * 100:.1f}%"  # noqa: E731
    lines = [
        "# Benchmark results",
        "",
        f"Generated by `benchmarks/run_benchmarks.py` on {started} (UTC). Do not edit by hand; rerun the script.",
        "",
        f"- Scenarios: {len(seeds)} seeded synthetic scenarios (default generator params), seeds {seeds[0]}–{seeds[-1]}.",
        f"- CP-SAT: time limit {args.time_limit:g} s, {args.workers} workers, solver seed 0. Baselines: greedy by priority, first-in first-out.",
        f"- Machine: {platform.processor() or platform.machine()}, {os.cpu_count()} logical CPUs, {platform.system()} {platform.release()}, Python {platform.python_version()}. Total run time {elapsed / 60:.1f} min.",
        f"- Validator violations across all {len(rows)} plans: **{viol}**.",
        "- Data: synthetic. These results describe this prototype on these scenarios only; they are not a claim about real operations.",
        "",
        "## Priority-weighted coverage (0–1, higher is better)",
        "",
        "| Planner | Mean | Median | Min | Max | Missions covered (mean) | Mean sortie risk (mean) |",
        "|---|---|---|---|---|---|---|",
    ]
    for n, label in (("fifo", "FIFO baseline"), ("greedy", "Greedy baseline"), ("cpsat", "CP-SAT optimiser")):
        lines.append(
            f"| {label} | {st.mean(pwc[n]):.3f} | {st.median(pwc[n]):.3f} | {min(pwc[n]):.3f} | {max(pwc[n]):.3f} "
            f"| {st.mean(cov[n]):.1f} | {st.mean(risk[n]):.3f} |" if risk[n] else
            f"| {label} | {st.mean(pwc[n]):.3f} | {st.median(pwc[n]):.3f} | {min(pwc[n]):.3f} | {max(pwc[n]):.3f} | {st.mean(cov[n]):.1f} | n/a |"
        )
    g, f = rel("cpsat", "greedy"), rel("cpsat", "fifo")
    wg, wf = wins("cpsat", "greedy"), wins("cpsat", "fifo")
    lines += [
        "",
        "## CP-SAT against the baselines",
        "",
        "| Comparison | Mean relative gain | Median relative gain | Better / equal / worse (scenarios) |",
        "|---|---|---|---|",
        f"| CP-SAT vs greedy | {pct(st.mean(g))} | {pct(st.median(g))} | {wg[0]} / {wg[1]} / {wg[2]} |",
        f"| CP-SAT vs FIFO | {pct(st.mean(f))} | {pct(st.median(f))} | {wf[0]} / {wf[1]} / {wf[2]} |",
        "",
        "Relative gain is (CP-SAT − baseline) / baseline in priority-weighted coverage, per scenario, over scenarios where the baseline is above zero.",
        "",
        "## CP-SAT solve time (seconds, wall clock, this machine)",
        "",
        f"Median {st.median(t):.1f} s, mean {st.mean(t):.1f} s, max {max(t):.1f} s. Status counts: "
        + ", ".join(f"{k} {v}" for k, v in sorted(statuses.items())) + ".",
        "",
        "Per-scenario rows: `benchmarks/results/results.csv`.",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")  # RESULTS.md uses typographic symbols
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--scenarios", type=int, default=20)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--time-limit", type=float, default=20.0)
    ap.add_argument("--workers", type=int, default=4)
    args = ap.parse_args()

    started = datetime.now(UTC).strftime("%Y-%m-%d %H:%M")
    t0 = time.perf_counter()
    rows: list[dict] = []
    for seed in range(args.seed, args.seed + args.scenarios):
        rows += run_one(seed, args.time_limit, args.workers)
        last = {r["planner"]: r for r in rows[-3:]}
        print(f"seed {seed}: " + "  ".join(
            f"{n} {last[n]['priority_weighted_coverage']:.3f} ({last[n]['wall_s']:.1f}s)" for n in PLANNERS), flush=True)

    (OUT_DIR / "results").mkdir(exist_ok=True)
    with open(OUT_DIR / "results" / "results.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(rows)
    md = summarise(rows, args, started, time.perf_counter() - t0)
    (OUT_DIR / "RESULTS.md").write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
